import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const read = rel => fs.readFileSync(path.join(root, rel), 'utf8')
const exists = rel => fs.existsSync(path.join(root, rel))
const pkg = JSON.parse(read('package.json'))
const config = JSON.parse(read('config/sakura.config.json'))

assert.match(pkg.version, /^2\.0\.0-rc\.(?:[5-9]|[1-9]\d+)$/)
assert.equal(config.bot.release, pkg.version)
assert.ok(config.tts && typeof config.tts === 'object', 'config.tts missing')
assert.ok(Object.hasOwn(config.tts, 'key'), 'tts.key missing')
assert.ok(Object.hasOwn(config.tts, 'region'), 'tts.region missing')
assert.ok(Array.isArray(config.tts.voices) && config.tts.voices.length >= 6, 'Microsoft voice catalog missing')
assert.match(read('data/microsoft-tts.js'), /tts\.speech\.microsoft\.com\/cognitiveservices\/v1/, 'official Microsoft Speech REST endpoint missing')
assert.match(read('data/microsoft-tts.js'), /Ocp-Apim-Subscription-Key/, 'Microsoft Speech authentication header missing')

const interactive = read('data/interactive.js')
const reply = read('data/reply.js')
const handler = read('data/handler.js')
const officialLinks = read('data/official-links.js')
assert.doesNotMatch(interactive, /\*atualizações:\*\s*\$\{settings\.updateChannel/, 'menu body must not print update URL')
assert.doesNotMatch(interactive, /\*grupo oficial da Sakura:\*\s*\$\{settings\.officialGroup/, 'menu body must not print group URL')
assert.match(officialLinks, /Atualizações/)
assert.match(officialLinks, /Grupo oficial da sakura/)
assert.match(officialLinks, /cta_url/)
assert.doesNotMatch(handler, /Atualizações oficiais da Sakura\./)
assert.doesNotMatch(handler, /sendOfficialLinksBar/)
assert.doesNotMatch(reply, /officialLinkActions|markCommandCta/)
assert.match(read('commands/menu.js'), /officialLinks:\s*true/)

const sticker = read('data/sticker-metadata.js')
const s = read('commands/s.js')
const take = read('commands/take.js')
assert.match(sticker, /sticker-pack-description/)
assert.match(sticker, /slice\(0,\s*512\)/, 'sticker description must allow multiline block')
assert.match(sticker, /Enviado por:/i)
assert.match(sticker, /Feita pela:\s*Sakurajima-Bot/i)
assert.match(sticker, /Grupo:/i)
assert.match(s, /buildSakuraStickerDescription/, 'sticker command .s must use Sakura multiline description')
assert.match(s, /metadata\?\.subject|groupName/, 'sticker command .s must use current group name')
assert.match(take, /stripStickerMetadata/, '.take must strip old metadata')
assert.match(take, /addExactStickerMetadata/, '.take custom must apply exact metadata')
assert.match(take, /vipOnly:\s*true/, '.take must be VIP-only')
const stickerMetadata = await import(new URL('../sticker-metadata.js', import.meta.url))
const description = stickerMetadata.buildSakuraStickerDescription({ userName: 'Drux', groupName: 'Grupo Sakura' })
assert.equal(description.split('\n').length, 3, 'sticker description must preserve three lines')
assert.match(description, /❄️ Enviado por: Drux/i)
assert.match(description, /💎 Feita pela: Sakurajima-Bot/i)
assert.match(description, /🧊 Grupo: Grupo Sakura/i)

assert.ok(exists('data/targets.js'), 'central target resolver missing')
const targetSource = read('data/targets.js')
assert.match(targetSource, /participantAlt/)
assert.match(targetSource, /context\?\.participant/)
assert.match(read('commands/tictactoe.js'), /firstTargetJid/, 'tic-tac-toe must use central target resolver')

const play = read('commands/play.js')
const music = read('data/music.js')
const playerCommand = read('commands/player.js')
assert.match(play, /yt-dlp/i)
assert.doesNotMatch(play, /Nexia|api\/musica|api\/ytmp3/i)
assert.match(music, /downloadWithYtDlp/)
assert.doesNotMatch(music, /Nexia/i)
assert.doesNotMatch(playerCommand, /Nexia/i)
assert.ok(!exists('data/player/nexia-sdk-player.js'), 'Nexia player runtime file must be removed')
assert.ok(!exists('data/vendor/nexia-sdk.cjs'), 'Nexia SDK vendor file must be removed')

assert.ok(exists('commands/tts.js'), 'TTS command missing')
assert.ok(exists('data/microsoft-tts.js'), 'Microsoft TTS adapter missing')
const tts = read('commands/tts.js')
assert.match(tts, /Microsoft/i)
assert.match(tts, /tts vozes|vozes/i)
assert.match(tts, /sendNativeList/)

const economyUi = read('data/economy-ui.js')
assert.match(economyUi, /title:\s*['"]PERFIL['"]/)
assert.doesNotMatch(economyUi, /foto:\* carregada do WhatsApp/i)
assert.doesNotMatch(economyUi, /PERFIL SAKURA/)
assert.doesNotMatch(interactive, /comandos organizados por função/i)
assert.match(interactive, /getCommandUsage\(command\)/, 'category rows should be able to show complete compact usage')
assert.match(read('commands/economy.js'), /\.lojade @pessoa/)

console.log('✅ RC5 media/UI: botões, CTA, stickers, menção por resposta, yt-dlp, TTS e menus aprovados')
